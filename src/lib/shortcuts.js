const WEB_PROTOCOLS = ['http:', 'https:']

const isWebUrl = url => {
  try {
    return WEB_PROTOCOLS.includes(new URL(url).protocol)
  } catch {
    return false
  }
}

/**
 * Whether a URL typed in the shortcut dialog is a web address. Refuses other
 * schemes (javascript:, data:…) and text with spaces, which some browsers
 * accept as a host once prefixed with https:// ("https://not a url").
 *
 * @param {string} url - URL to check
 * @returns {boolean}
 */
export const isValidShortcutUrl = url => !/\s/.test(url) && isWebUrl(url)

/**
 * Returns the URL if it can be used as the href of a shortcut tile.
 *
 * @param {string} url - URL read from a shortcut file
 * @returns {string|undefined}
 */
export const getSafeShortcutHref = url => (isWebUrl(url) ? url : undefined)

/**
 * Content of a .url shortcut file, in the format generated by cozy-stack.
 *
 * @param {string} url - target of the shortcut
 * @returns {string}
 */
export const makeShortcutFileContent = url =>
  `[InternetShortcut]\r\nURL=${url}\r\n`

export const SHORTCUT_MIME_TYPE = 'application/internet-shortcut'
